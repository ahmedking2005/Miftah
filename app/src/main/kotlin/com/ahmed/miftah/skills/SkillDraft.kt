package com.ahmed.miftah.skills

/** One tool call from a completed agent run, as recorded by the chat UI. */
data class ToolUse(
    val name: String,
    val argumentsJson: String,
    val result: String
)

/**
 * Builds a SKILL.md draft from a completed agent run (Feature 2: agent-created
 * skills, Hermes-style). The deterministic template is built purely from the
 * recorded tool calls; a model-written draft, when available, supplies name,
 * description and body — but allowed-tools is ALWAYS recomputed here as
 * "tools actually used ∩ registered tools", never taken from model output.
 * Pure — JVM-testable.
 */
object SkillDraft {

    /** The minimum tool calls for a run to be worth saving as a skill. */
    const val MIN_TOOL_CALLS = 2

    fun isWorthSaving(uses: List<ToolUse>): Boolean = uses.size >= MIN_TOOL_CALLS

    /** Tools actually used, de-duplicated in first-use order, intersected with the registered set. */
    fun allowedToolsFor(uses: List<ToolUse>, registeredTools: Set<String>): List<String> =
        uses.map { it.name }.distinct().filter { it in registeredTools }

    /** URL-style slug from the goal text; falls back to a fixed name when nothing usable remains. */
    fun slugify(goal: String): String {
        val slug = goal.lowercase()
            .replace(Regex("[^a-z0-9]+"), "-")
            .trim('-')
            .take(40)
            .trim('-')
        return slug.ifEmpty { "saved-workflow" }
    }

    private fun oneLine(text: String, max: Int): String {
        val flat = text.replace(Regex("\\s+"), " ").trim()
        return if (flat.length <= max) flat else flat.take(max - 1) + "…"
    }

    /** Deterministic draft built from the recorded calls alone (the offline/model-failure path). */
    fun template(goal: String, uses: List<ToolUse>, registeredTools: Set<String>): ParsedSkill {
        val body = buildString {
            append("## Goal\n\n").append(goal.trim()).append("\n\n## Steps\n\n")
            uses.forEachIndexed { i, use ->
                append(i + 1).append(". Called `").append(use.name).append("` with ")
                    .append(oneLine(use.argumentsJson, 200)).append('\n')
                val result = oneLine(use.result, 240)
                if (result.isNotEmpty()) append("   → ").append(result).append('\n')
            }
            append(
                "\n## Notes\n\nDraft generated by Miftah from a completed chat run. " +
                    "Review and edit before enabling; follow the same steps when a similar request comes up.\n"
            )
        }
        return ParsedSkill(
            name = slugify(goal),
            description = oneLine(goal, 120),
            allowedTools = allowedToolsFor(uses, registeredTools),
            body = body.trim()
        )
    }

    /**
     * Adopts a model-written SKILL.md when it parses to a usable name and body;
     * returns null otherwise (caller falls back to [template]). allowed-tools
     * is recomputed from the recorded calls regardless of what the model wrote.
     */
    fun fromModelMarkdown(
        markdown: String,
        uses: List<ToolUse>,
        registeredTools: Set<String>,
        fallbackGoal: String
    ): ParsedSkill? {
        val parsed = SkillParser.parse(markdown, slugify(fallbackGoal))
        if (parsed.body.isBlank() || parsed.name.isBlank()) return null
        return parsed.copy(allowedTools = allowedToolsFor(uses, registeredTools))
    }

    /** Renders a draft as SKILL.md text that [SkillParser] reads back losslessly. */
    fun toMarkdown(skill: ParsedSkill): String = buildString {
        append("---\n")
        append("name: ").append(skill.name.replace(Regex("\\s+"), " ").trim()).append('\n')
        append("description: ").append(oneLine(skill.description, 200)).append('\n')
        if (skill.allowedTools.isNotEmpty()) {
            append("allowed-tools: [").append(skill.allowedTools.joinToString(", ")).append("]\n")
        }
        append("---\n\n")
        append(skill.body.trim()).append('\n')
    }
}
